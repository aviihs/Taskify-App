/// Icon size scale — keeps touch targets and visual weight consistent.
abstract final class AppIconSize {
  static const double xs = 14;
  static const double sm = 16;
  static const double md = 20;
  static const double lg = 22;
  static const double xl = 24;
  static const double xxl = 32;

  /// Inline list / row actions.
  static const double listAction = sm;

  /// App bar leading / trailing.
  static const double appBar = md;

  /// Empty state hero icon inside container.
  static const double emptyState = xxl;
}
